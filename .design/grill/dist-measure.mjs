#!/usr/bin/env node
// dist-measure.mjs — measure the BUILT pages in Firefox without a web server.
//
//   node .design/grill/dist-measure.mjs <distDir> <route> <measure.js> [width] [height]
//   e.g. node .design/grill/dist-measure.mjs dist/client / .design/grill/render-measure.js 1240 1400
//
// Why this exists next to page-measure.mjs: Astro writes every asset URL absolute — `/_astro/...` in
// href/src/srcset AND `url(/_astro/...)` inside the built CSS — and a file:// page resolves `/` at the
// filesystem root, so a copied dist/client/index.html loads with no CSS and no @font-face and every
// measurement is wrong. Serving dist over loopback http was tried first and measured as a failure on
// this rig: under `--screenshot` firefox fetches `GET /` and then never fetches the subresources, and
// the run dies at the timeout (Linux/x64, Firefox 158.0.1). So: rewrite the URLs to relative, in copies
// that sit inside dist, and let page-measure.mjs do the browser part exactly as it does for a specimen.
//
// Copies are named `.rel.css` / `rendered-*.html` and are never written over an artifact: dist/ is
// regenerated by `npm run build`, and a measurement step must not mutate what gets deployed.
//
// What it does NOT cover: the island's client-side fetch (there is no API on file://). The markup that
// gets measured is the server-rendered branch — which is the branch a JavaScript-off visitor sees, and
// DESIGN.md requires that branch to exist regardless.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, unlinkSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, resolve, basename, dirname } from 'node:path';

const [distArg, route = '/', measureArg, w = '1240', h = '1400'] = process.argv.slice(2);
if (!distArg || !measureArg) {
  console.error('usage: node .design/grill/dist-measure.mjs <distDir> <route> <measure.js> [w] [h]');
  process.exit(2);
}
const dist = resolve(distArg);
const assetDir = join(dist, '_astro');
if (!existsSync(assetDir)) { console.error(`no _astro directory under ${dist} — run npm run build first`); process.exit(2); }

// 1. rewritten CSS copies, alongside the originals so `url(./x.woff2)` resolves
let cssCopies = 0;
for (const f of readdirSync(assetDir)) {
  if (!f.endsWith('.css') || f.endsWith('.rel.css')) continue;
  // The copy lives INSIDE _astro, so a hashed-asset url drops the _astro segment (./x.woff2) and a
  // public-dir url goes up one (../x.png). Getting this wrong is silent and expensive: the woff2 404s,
  // the face sits at "loading" forever, and every height the gate reports is a fallback metric — which
  // is exactly why the gate now fails on a ratified face that never loads.
  const css = readFileSync(join(assetDir, f), 'utf8')
    .replace(/url\((['"]?)\/_astro\//g, 'url($1./')
    .replace(/url\((['"]?)\/(?!\/)/g, 'url($1../');
  writeFileSync(join(assetDir, f.replace(/\.css$/, '.rel.css')), css);
  cssCopies++;
}

// 2. the page copy, with href/src/srcset made relative and the CSS link pointed at the copy
const dir = join(dist, route === '/' ? '' : route.replace(/^\//, ''));
// Astro writes a 404 page as a sibling FILE (404.html), not a directory with index.html
const srcPage = [dir, join(dir, 'index.html'), `${dir}.html`, join(dist, `${route.replace(/^\//, '')}.html`)]
  .find((p) => existsSync(p) && statSync(p).isFile());
if (!srcPage) { console.error(`no page for route ${route} under ${dist}`); process.exit(2); }
const probeDir = dirname(srcPage);
const depth = probeDir === dist ? 0 : probeDir.split('/').length - dist.split('/').length;
const rel = depth === 0 ? './' : '../'.repeat(depth);
let html = readFileSync(srcPage, 'utf8')
  .replace(/((?:href|src|srcset|content)=")\/(?!\/)/g, '$1' + rel)
  .replace(new RegExp(`(${rel})_astro/([A-Za-z0-9._-]+)\\.css`, 'g'), `$1_astro/$2.rel.css`);

const probe = join(probeDir, `rendered-${route === '/' ? 'index' : route.replace(/[\/]/g, '-')}.html`);
writeFileSync(probe, html);
console.error(`probing ${basename(probe)} — ${cssCopies} rewritten css copies, asset prefix ${rel}`);
try {
  execFileSync(process.execPath, ['.design/grill/page-measure.mjs', probe, resolve(measureArg), w, h], { stdio: 'inherit' });
} finally {
  // page-measure removes its own .measured-* copy; this one is ours, and it sits inside the artifact
  // that gets uploaded — never leave a probe file in dist
  try { unlinkSync(probe); } catch {}
}
