// Regenerates `public/book-club-social-share.jpg` — the image `og:image` / `twitter:card` point at
// (src/layouts/Layout.astro declares 1200x630 to match). `npm run assets:social`; needs no credentials and
// no network, but does need firefox, because the card is composed by the browser.
//
// What changed and why (apply 4g). The old card was the photo with a scrim: it took
// `src/assets/math-group-image.jpg`, darkened the bottom, and wrote white type over it in `#f59e0b`. Three
// problems at once:
//   - `#f59e0b` is retired. It is delta-OKLab 0.019 from Amazon orange, it reads 2.06 as text on paper, and
//     `ratify-check` asserts it is absent from `@theme` — while the published card kept painting it
//     (D82/D88). `npm run check:social` now fails on it.
//   - the photo is a stock Unsplash crowd shot whose provenance is recorded nowhere in the repo
//     (`.notes/asset-sources.md`: "Provenance **not recorded anywhere**… who took it, may we publish it"),
//     and D86 rules stock crowd photography out because it "shows people who have never attended"; D94 adds
//     that the club has no member photography at all, so the site is photo-free by construction. The share
//     card is the most widely seen surface on the site and was the one place a stranger's face was
//     unavoidable. This card has no photo, so it cannot drift back into that.
//   - the type was `font-family="sans-serif"` at invented sizes (70 / 34): whatever the machine's fontconfig
//     happened to resolve, and not one of the ratified faces.
//
// How it is made now, and what that buys:
//   1. the token block is the palette. `@theme` in `src/styles/global.css` is copied verbatim into the card
//      document, so the card's colours are the site's colours and cannot drift.
//   2. firefox composes it, through the same `page-measure.mjs` loop the design gates use, so the renderer
//      that measures the site is the renderer that made these pixels, and the ratified faces (PT Serif
//      400/700, Public Sans Variable) are the ones actually drawn — proved by the page's own
//      `document.fonts.load()` result, which the generator refuses to ignore.
//   3. the layout is one screen of the site at the site's desktop width: kicker `text-label`, club name
//      `text-display-4` (the one display step, on the locator — D112), focus line `text-heading` in the
//      serif, paths row in the footer's grammar (D115) with the path hues naming the services (D106). Sizes
//      are read out of `@theme`, never typed here.
//   4. `scripts/check-social-card.mjs` then measures the written JPEG's painted bytes (D116): ground dark,
//      no amber anywhere, every band's ink clear of the 4.5 text bar (3.0 for drawn marks), each path word
//      painted at the hue its token's bytes produce, and the ink extent in the pixels matching the run width
//      the page laid out — the guard against firefox screenshotting before a webfont applies, which is a
//      real race whose failure mode is a card that looks fine and is set in DejaVu.
//
// Copy rules: no cadence word. `src/config.json`'s description says "Monthly meetups" while the hero says
// "Monthly Meetups" and the old hero said "Weekly" — that contradiction is the operator's to settle (D26),
// so the card stays out of it. No date either: a card regenerated by hand would claim an age it cannot
// compute (D103). Everything printed here is grounded in this repo: the club's name and city
// (`src/config.json`'s `seo`), the domain (`seo.canonical`), the two paths (`URLs`), and the focus line
// (`src/components/HeroSection.astro`: "Current Focus: Number Theory and Abstract Algebra" — the one string
// the card cannot derive from config today; hoisting it into `src/config.json` so both read one value is the
// follow-up).
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';
import { BANDS, MOTIF, checkCard } from './check-social-card.mjs';
// The domain is read out of src/config.json rather than typed here, so the card cannot claim an address the
// site does not own. Parsed with fs because node's JSON modules expose only a default export, while astro
// imports the same file with named bindings - the parse is the portable half.
const config = JSON.parse(fs.readFileSync(path.resolve('src/config.json'), 'utf8'));
const DOMAIN = new URL(config.seo.canonical).host;
if (config.seo.image !== '/book-club-social-share.jpg') console.warn('NOTE: src/config.json seo.image is ' + config.seo.image + ', but this script writes public/book-club-social-share.jpg');

const W = 1200;
const H = 630;
const PAD = 70;
const root = process.cwd();
const out = path.resolve('public/book-club-social-share.jpg');
const html = path.resolve('.design/tmp-card.html');
const png = path.resolve('.design/tmp-card.png');

// ---- 1. palette and ramp come from the token block, not from this file. ----
const css = fs.readFileSync(path.resolve('src/styles/global.css'), 'utf8');
const at = css.indexOf('@theme');
const open = css.indexOf('{', at);
let depth = 0, end = -1;
for (let i = open; i < css.length; i++) {
  if (css[i] === '{') depth++;
  else if (css[i] === '}' && --depth === 0) { end = i; break; }
}
if (end < 0) { console.error('could not find the @theme block in src/styles/global.css'); process.exit(1); }
// @theme's custom properties are plain custom properties, so the block transfers verbatim.
const theme = css.slice(open + 1, end);
const token = (name) => {
  const m = theme.match(new RegExp(`--${name}:\\s*([^;]+);`));
  if (!m) { console.error(`--${name} is not in @theme — the card cannot be built without it`); process.exit(1); }
  return m[1].trim();
};

// ---- 2. geometry is the checker's table, so composer and verifier cannot disagree. ----
const band = (name) => BANDS.find((b) => b.name === name);
const place = (name, step) => {           // centred in the band on the token's own line height
  const b = band(name);
  const lh = parseInt(token(`text-${step}--line-height`), 10);
  return { top: b.y0 + (b.y1 - b.y0 - lh) / 2, lh, size: token(`text-${step}`) };
};
const kicker = place('kicker', 'label');
const title = place('title', 'display-4');
const lede = place('lede', 'heading');
const focus = place('focus', 'micro');
const paths = place('paths', 'lede');
const scale = MOTIF.width / MOTIF.vbW;

