fs.mkdirSync(path.dirname(html), { recursive: true });
fs.writeFileSync(html, doc);

// ---- 3. firefox composes it, and the page reports its own layout. ----
fs.rmSync(png, { force: true });
const shot = execFileSync(process.execPath, [
  '.design/grill/page-measure.mjs', path.relative(root, html), 'scripts/social-card-measure.js',
  String(W), String(H), png,
], { encoding: 'utf8' });
const posted = JSON.parse(shot.slice(shot.indexOf('{'), shot.lastIndexOf('}') + 1));
if (!posted.done) { console.error('the card page did not report: ' + shot); process.exit(1); }
const dead = Object.entries(posted.faces ?? {}).filter(([, v]) => !v).map(([k]) => k);
if (dead.length) { console.error('these faces did not load, so the card would be set in a fallback:\n  ' + dead.join('\n  ')); process.exit(1); }

// ---- 4. PNG -> JPEG, exactly 1200x630. JPEG because every crawler that reads og:image accepts JPEG and
// none is guaranteed to accept AVIF. ----
await sharp(png)
  .resize(W, H, { fit: 'cover', position: 'centre' })
  .toColourspace('srgb')
  .withMetadata({ icc: 'srgb' })
  .jpeg({ quality: 82, progressive: true, mozjpeg: true })
  .toFile(out);

// ---- 5. the page's own report becomes evidence: npm run check:social re-checks the committed JPEG against
// it without firefox. Tracked in git (like .design/fonts/*.json) because it is the other half of the claim:
// "these pixels are what this document painted, in these faces, at these sizes".
fs.writeFileSync(path.resolve('.design/card-page.json'), JSON.stringify(posted, null, 1) + '\n');

// ---- 6. measure what was actually painted, and refuse to call it done otherwise. ----
const r = await checkCard(out, { page: posted });
console.log(`\n== ${path.relative(root, out)} — ${fs.statSync(out).size} bytes (jpeg q82) ==`);
console.log(r.lines.join('\n'));
console.log(`\n  faces: ${Object.entries(posted.faces).map(([k, v]) => `${k}=${v}`).join(', ')}`);
console.log('  ground (author syntax, from the page): ' + posted.ground);
console.log('  runs: ' + posted.runs.map((x) => `${x.band}: ${x.face} ${x.size}/${x.weight}, ${x.width}px wide, colour ${x.color}`).join('\n         '));
if (!r.ok) { console.error('\nSOCIAL CARD: FAIL — the artifact was written, but it is not acceptable. Not committed by this script.'); process.exit(1); }
console.log('\nSOCIAL CARD: PASS');
