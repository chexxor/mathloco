#!/usr/bin/env node
/**
 * build-probe.mjs - generates `n8n/env-probe.json`: a five-node, **read-only** workflow that answers, in one
 * click on the n8n host, the four questions this repo cannot answer from a delegate's seat.
 *
 *   node integrations/mobilizon-cadence/build-probe.mjs          # write the artifact
 *   node integrations/mobilizon-cadence/build-probe.mjs --check  # validate, write nothing, exit 1 on a problem
 *
 * Why it exists. `https://n8n.labradorius.com` sits behind the YunoHost SSO, so from outside that host the
 * cadence's own preconditions are unverifiable. Measured again 2026-11-04: `/`, `/healthz`, `/api/v1/workflows`
 * and `/mcp-server/http` all answer `302 -> labradorius.com/yunohost/sso`, and `192.168.1.120:5678` is
 * unreachable from this worktree. The four unknowns, each of which is a 09:00 failure waiting to happen:
 *
 *   1. may Code nodes see `$env`? (`N8N_BLOCK_ENV_ACCESS_IN_NODE` - and the install shape decides it: Docker,
 *      bare metal, PM2; nothing outside that host knows which)
 *   2. can that host reach Mobilizon at all? (n8n in a container can have a different resolver than the browser)
 *   3. does the **path** cadence posts to answer from inside that network? (the apex answering is not that)
 *   4. what clock does the host think it runs? (the trigger's 09:00 is `settings.timezone`, the host may be UTC)
 *
 * Why a generated artifact rather than a snippet in the guide (D183, applying D179's rule to a second file): a
 * hand-typed Code node cannot be gated, and the thing worth gating here is that the probe **cannot write**.
 * `checkProbe()` is the argument, and `test/import.test.mjs` plants the counterfactuals into it (a schedule
 * trigger, a returned `$env` value, a mutation in the POST body, an attached credential) so the argument is
 * proven to fire rather than merely to pass. `check.mjs` rebuilds and re-checks it on every run.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const CHECK = process.argv.includes("--check");
const config = await import(new URL("./series.config.mjs", import.meta.url).href);
const { INSTANCE, CREDENTIALS } = config;
const OUT = new URL("./n8n/env-probe.json", import.meta.url);

export const PROBE_NAME = "Mobilizon cadence - environment probe (read only)";
export const NODEINFO_PATH = "/.well-known/nodeinfo/2.0";
export const TYPE_NAME_QUERY = "{ __typename }";  // measured 2026-11-04: 200 {"data":{"__typename":"RootQueryType"}}

export const PROBE_NAMES = {
  run: "P0 Run me (there is no schedule here)",
  env: "P1 What this host can see",
  apex: "P2 Mobilizon on the apex",
  gql: "P3 Mobilizon on the GraphQL path",
  report: "P4 Report what I found",
};

const HEADERS = [{ name: "accept", value: "application/json" }];

/**
 * P1 - the host. Presence, never values: an env probe that prints a password into an execution log is a worse
 * instrument than no probe, and this workflow keeps execution data (`saveDataSuccessExecution: all`).
 */
const envCode = `// GENERATED by build-probe.mjs - do not edit here; edit build-probe.mjs and rebuild.
// Presence only. The two names come from series.config.mjs, so renaming them there moves this node too.
const WANTED = ${JSON.stringify([CREDENTIALS.emailEnv, CREDENTIALS.passwordEnv])};
const present = (name) => {
  try { return typeof $env?.[name] === "string" && $env[name].length > 0; } catch (e) { return false; }
};
let visible = false, keys = [];
try { visible = typeof $env === "object" && $env !== null; keys = Object.keys($env ?? {}); } catch (e) { visible = false; }
return [{ json: {
  envVisible: visible,
  envKeyCount: keys.length,
  wantedNames: WANTED,
  wantedPresent: WANTED.filter(present),
  wantedMissing: WANTED.filter((n) => !present(n)),
  // n8n blocks env access in Code nodes, and in HTTP node expressions, under the same host setting
  // N8N_BLOCK_ENV_ACCESS_IN_NODE. That is a host-level fix, not a workflow one.
  hostClockUtc: new Date().toISOString(),
  hostOffsetMinutes: new Date().getTimezoneOffset(),
  hostIsoTimezone: (() => { try { return Intl.DateTimeFormat().resolvedOptions().timeZone ?? null; } catch (e) { return null; } })(),
  valuesPrinted: false,
} }];`;

/**
 * P4 - the verdict, written so the whole answer is one string: the operator runs it once and pastes `summary`
 * back to a delegate without needing the n8n UI to interpret it.
 */
const reportCode = `// GENERATED by build-probe.mjs - do not edit here; edit build-probe.mjs and rebuild.
const seen = $('${PROBE_NAMES.env}').item.json;
const apex = $('${PROBE_NAMES.apex}').item.json ?? {};
const gql = $('${PROBE_NAMES.gql}').item.json ?? {};
const soft = apex.software ?? null;
// A GraphQL response nests its payload under "data"; n8n puts the parsed body at the item root. Accept
// either, because which one appears depends on the node's response format, and a probe that reports
// "NO ANSWER" for a response it did receive is worse than no probe. (No backticks anywhere in here: a
// backtick inside these template literals would close the builder's string - caught, 2026-11-04.)
const typeName = (gql.data && gql.data.__typename) || gql.__typename || null;
const verdicts = [];

if (!seen.envVisible) {
  verdicts.push('CODE: env access is blocked in Code nodes (N8N_BLOCK_ENV_ACCESS_IN_NODE). The cadence reads the Mobilizon password in node 03\\'s HTTP expression, which is governed by the same setting - so this is host-level: unset it, or restart n8n with the variables present.');
}
for (const n of seen.wantedMissing) {
  verdicts.push('CODE: ' + n + ' is not in the environment n8n started with. Set it in the service environment (systemd drop-in / container env file), then RESTART n8n - it reads its environment at process start.');
}
if (!soft) {
  verdicts.push('HOST: ${INSTANCE.baseUrl} gave no nodeinfo software field - this host cannot reach it, or something else answered. Check DNS from inside n8n\\'s network namespace.');
} else if (soft.name !== 'Mobilizon') {
  verdicts.push('HOST: something answered as "' + soft.name + '", not Mobilizon - a proxy is intercepting the request.');
}
if (typeName) {
  verdicts.push('OK: ${INSTANCE.graphqlPath} answers from this host (root type ' + typeName + '), so nodes 02/03/06/07 can reach it.');
} else {
  verdicts.push('HOST: ${INSTANCE.baseUrl}${INSTANCE.graphqlPath} did not answer { __typename } - the cadence\\'s own endpoint is unreachable from this host. That is the 09:00 failure this probe exists to catch.');
}

const lines = [
  'cadence environment probe - read only, nothing was written',
  'asked at   ' + seen.hostClockUtc + ' (the n8n host clock; offset ' + seen.hostOffsetMinutes + ' min; host zone ' + seen.hostIsoTimezone + ')',
  'trigger    cadence fires at 09:00 in its own settings.timezone = ${INSTANCE.timezone ?? "America/Chicago"}, which need not be the host zone above',
  'target     ${INSTANCE.baseUrl}${INSTANCE.graphqlPath}',
  'nodeinfo   ' + (soft ? soft.name + ' ' + soft.version : 'no answer') + ' at ${NODEINFO_PATH}',
  'graphql    ' + (typeName ? 'answers, root type ' + typeName : 'NO ANSWER'),
  'env        ' + (seen.envVisible ? 'visible, ' + seen.envKeyCount + ' keys; wanted: ' + (seen.wantedPresent.join(', ') || 'none of them') : 'BLOCKED in Code nodes'),
];
if (soft && soft.version === '5.2.4') lines.push('version    matches the version every query in this repo was probed against');
if (soft && soft.version !== '5.2.4') lines.push('version    ' + soft.version + ' - it was probed at 5.2.4; re-run node integrations/mobilizon-cadence/check.mjs before trusting a field name');
if (verdicts.length) lines.push('', 'needs attention:');
for (const v of verdicts) lines.push('- ' + v);
lines.push('', 'This workflow has no schedule trigger and no credential: import it, run it once, read the summary, delete it.');
return [{ json: { ok: verdicts.length === 0, verdicts, summary: lines.join('\\n'), host: seen, software: soft } }];`;

export function buildProbe() {
  const nodes = [
    {
      id: "probe-run", name: PROBE_NAMES.run, type: "n8n-nodes-base.manualTrigger", typeVersion: 1,
      position: [-760, -160], parameters: {},
    },
    {
      id: "probe-env", name: PROBE_NAMES.env, type: "n8n-nodes-base.code", typeVersion: 2,
      position: [-560, -160], parameters: { mode: "runOnceForAllItems", jsCode: envCode },
    },
    {
      id: "probe-apex", name: PROBE_NAMES.apex, type: "n8n-nodes-base.httpRequest", typeVersion: 4,
      position: [-360, -160],
      parameters: {
        method: "GET", url: `${INSTANCE.baseUrl}${NODEINFO_PATH}`, sendQuery: false,
        options: { response: { response: { neverError: false } }, headers: HEADERS },
      },
    },
    {
      id: "probe-gql", name: PROBE_NAMES.gql, type: "n8n-nodes-base.httpRequest", typeVersion: 4,
      position: [-160, -160],
      // The one POST in this file, and it asks a type name. It is here because the apex answering does not
      // prove the path cadence posts to answers from *this* host.
      parameters: {
        method: "POST", url: `${INSTANCE.baseUrl}${INSTANCE.graphqlPath}`, sendQuery: false,
        options: { response: { response: { neverError: false } }, headers: [...HEADERS, { name: "content-type", value: "application/json" }] },
        sendBody: true, specifyBody: "json", jsonBody: JSON.stringify({ query: TYPE_NAME_QUERY }),
      },
    },
    {
      id: "probe-report", name: PROBE_NAMES.report, type: "n8n-nodes-base.code", typeVersion: 2,
      position: [40, -160], parameters: { mode: "runOnceForAllItems", jsCode: reportCode },
    },
  ];

  const connections = {
    [PROBE_NAMES.run]: { main: [[{ node: PROBE_NAMES.env, type: "main", index: 0 }]] },
    [PROBE_NAMES.env]: { main: [[{ node: PROBE_NAMES.apex, type: "main", index: 0 }]] },
    [PROBE_NAMES.apex]: { main: [[{ node: PROBE_NAMES.gql, type: "main", index: 0 }]] },
    [PROBE_NAMES.gql]: { main: [[{ node: PROBE_NAMES.report, type: "main", index: 0 }]] },
  };

  return {
    name: PROBE_NAME,
    nodes,
    connections,
    settings: {
      executionOrder: "v1",
      timezone: INSTANCE.timezone ?? "America/Chicago",
      saveDataErrorExecution: "all",
      saveDataSuccessExecution: "all",
      savePreExecutionData: false,
    },
    meta: { templateCredsSetupCompleted: false },
    tags: ["mobilizon", "cadence-probe"],
  };
}

/**
 * The read-only argument, as a function so a test can break it on purpose.
 * Returns [] when the document is a probe this repo would ship; otherwise the reasons it is not.
 */
export function checkProbe(wf) {
  const problems = [];
  const nodes = wf.nodes ?? [];
  const nodeNames = new Set(nodes.map((n) => n.name));
  const json = JSON.stringify(wf);

  // 1. Nothing here may fire on a clock or answer an inbound request. A read-only instrument that schedules
  //    itself has become a recurring job; one that listens has become a surface.
  for (const n of nodes) {
    if (/trigger/i.test(n.type) && n.type !== "n8n-nodes-base.manualTrigger") {
      problems.push(`${n.name}: ${n.type} would make the probe run on its own - only manualTrigger is allowed here`);
    }
    if (/webhook|formTrigger|chatTrigger/i.test(n.type)) problems.push(`${n.name}: ${n.type} opens an inbound surface; the probe is run by a person`);
  }

  // 2. Every request goes to the configured instance, over HTTPS, with no query string (a token in a query
  //    string is a token in an access log) and no swallowed error (silence would read as a pass).
  const http = nodes.filter((n) => n.type === "n8n-nodes-base.httpRequest");
  if (http.length !== 2) problems.push(`the probe holds exactly two requests (nodeinfo, __typename); found ${http.length}`);
  for (const n of http) {
    const u = new URL(n.parameters.url);
    if (u.origin !== new URL(INSTANCE.baseUrl).origin) problems.push(`${n.name}: ${u.origin} is not the configured instance`);
    if (u.protocol !== "https:") problems.push(`${n.name}: ${u.protocol} - plaintext from a host that holds the Mobilizon environment variables`);
    if (n.parameters.sendQuery) problems.push(`${n.name}: sendQuery is on`);
    if (n.parameters.options?.response?.response?.neverError) problems.push(`${n.name}: neverError hides a failure`);
  }

  // 3. The one POST asks a type name and nothing else, and no cadence document appears anywhere.
  const posts = http.filter((n) => n.parameters.method === "POST");
  if (posts.length !== 1) problems.push(`expected exactly one POST, found ${posts.length}`);
  for (const n of posts) {
    if (n.parameters.jsonBody !== JSON.stringify({ query: TYPE_NAME_QUERY })) {
      problems.push(`${n.name}: its body is not the literal { __typename } read - the probe sends nothing else`);
    }
    if (new URL(n.parameters.url).pathname !== INSTANCE.graphqlPath) problems.push(`${n.name}: not the path 5.2.4 serves (${INSTANCE.graphqlPath})`);
  }
  if (/\bmutation\b/i.test(json)) problems.push("the probe contains the word mutation");
  for (const forbidden of ["createEvent", "updateEvent", "deleteEvent", "login(", "organizedEvents", "preferredUsername"]) {
    if (json.includes(forbidden)) problems.push(`the probe references "${forbidden}" - that is cadence's surface, not a probe's`);
  }

  // 4. No credential, no header that could carry one.
  for (const n of nodes) {
    if (n.credentials && Object.keys(n.credentials).length) problems.push(`${n.name}: carries an n8n credential block - the probe needs none`);
    for (const h of n.parameters?.options?.headers ?? []) {
      if (/authorization|cookie|x-api-key/i.test(h.name)) problems.push(`${n.name}: header ${h.name} - the probe authenticates as nobody`);
    }
  }

  // 5. The returned object may not name $env at all: whatever leaves this node is derived (a boolean, a count,
  //    a name), never a value. Above the return, $env may be read in exactly two shapes, listed here rather
  //    than pattern-matched, so a new read is a decision someone has to make deliberately.
  const ALLOWED_ENV_READS = [
    'typeof $env?.[name] === "string"',
    '$env[name].length > 0',
  ];
  for (const n of nodes.filter((x) => x.type === "n8n-nodes-base.code")) {
    const code = n.parameters.jsCode ?? "";
    const at = code.indexOf("return [{");
    if (at < 0) problems.push(`${n.name}: no return found - the node emits nothing`);
    else if (code.slice(at).includes("$env")) problems.push(`${n.name}: $env appears in what the node returns - only a presence boolean may leave this node`);
    let rest = code;
    for (const a of ALLOWED_ENV_READS) rest = rest.split(a).join("");
    if (/\$env\s*(\?\.)?\[/.test(rest)) problems.push(`${n.name}: reads $env[...] somewhere other than the two allowed presence tests`);
    try { new Function("$", "$json", code); }
    catch (e) { problems.push(`${n.name}: the Code node does not parse: ${e.message}`); }
  }

  // 6. The graph is one straight line, names resolve, and the env names come from the one config.
  for (const [from, ports] of Object.entries(wf.connections ?? {})) {
    if (!nodeNames.has(from)) problems.push(`connections reference ${from}, which is not a node`);
    for (const list of Object.values(ports)) for (const arr of list ?? []) {
      for (const c of arr ?? []) if (!nodeNames.has(c.node)) problems.push(`${from} -> ${c.node}: no such node`);
    }
    if (ports.error) problems.push(`${from}: an error branch in a probe is a second path to read; a red execution is the finding`);
  }
  for (const m of json.matchAll(/\$\('([^']+)'\)/g)) {
    if (!nodeNames.has(m[1])) problems.push(`$('${m[1]}') names a node that does not exist`);
  }
  const envNode = nodes.find((n) => (n.parameters?.jsCode ?? "").includes("const WANTED"));
  const wantedLiteral = JSON.stringify([CREDENTIALS.emailEnv, CREDENTIALS.passwordEnv]);
  if (!envNode) problems.push("no probe node declares the env names to look for");
  else if (!envNode.parameters.jsCode.includes(`const WANTED = ${wantedLiteral}`)) {
    problems.push(`the probe's name list is not what series.config.mjs declares (${wantedLiteral}) - so it is checking names nobody set`);
  }
  if (wf.settings?.executionOrder !== "v1") problems.push("settings.executionOrder is not v1 - the older order evaluates expressions differently than every test here assumes");
  return problems;
}

// When imported (test/import.test.mjs plants counterfactuals into checkProbe) only the exports run.
const isMain = process.argv[1] && resolve(process.argv[1]) === import.meta.filename;
if (isMain) {
  const workflow = buildProbe();
  const problems = checkProbe(workflow);
  const json = JSON.stringify(workflow, null, 2);

  // Artifact drift - the same rule as the main workflow, and the reason verify-import.mjs can trust a baseline.
  if (CHECK) {
    let onDisk = null;
    try { onDisk = readFileSync(OUT, "utf8"); }
    catch { problems.push(`${OUT.pathname} does not exist - run: node integrations/mobilizon-cadence/build-probe.mjs`); }
    if (onDisk !== null && onDisk !== json + "\n") {
      problems.push(`${OUT.pathname} is stale: not what build-probe.mjs produces. Rebuild and commit it.`);
    }
  }

  if (problems.length) {
    console.error(`cadence probe build blocked:\n- ${problems.join("\n- ")}`);
    process.exit(1);
  }

  if (CHECK) {
    console.log(`cadence probe ok: ${workflow.nodes.length} nodes, manual trigger only, 2 read-only requests, no credential`);
  } else {
    writeFileSync(OUT, json + "\n");
    console.log(`built ${OUT.pathname}: ${workflow.nodes.length} nodes, ${json.split("\n").length} lines of JSON`);
    console.log(`it prints presence of ${CREDENTIALS.emailEnv}/${CREDENTIALS.passwordEnv}, never their values; nothing anywhere is written`);
  }
}
