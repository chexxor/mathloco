// render-gate-selftest.mjs — can the hero mark's checks in `check:render` fail, or do they only ever nod?
//
//   node design/render-gate-selftest.mjs        # needs a built dist/ and firefox; ~1 s per case
//   node design/render-gate-selftest.mjs "paint" # a substring picks which cases to run
//
//
// It always passes --no-build: the gate builds by default, and rebuilding would restore the page the
// mutation just broke, turning every case into a pass that proves nothing.
//
// D118's rule, applied to the gate that measures the mark: a pixel/layout gate needs a control that can
// fail, because the failure mode of a gate is not a wrong number, it is a green line on a broken page.
// `check:social` has `--selftest`; this is the same idea for the render gate's mark and control sections —
// the control cases are the counterfactual for D139/D140 (see the notes on cases 6a-6c).
//
// How it mutates: it edits **dist/client/index.html**, the built page, because that is what the gate
// measures — a specimen would prove the harness works but not that the gate reads the artifact. dist/ is
// regenerated by `npm run build` and is gitignored, so this touches no source and no artifact; the
// original page is restored in a finally block, and the script refuses to run if a mutation did not
// change the file (a mutation that matches nothing is how a selftest goes quietly green).
//
// Each case must come back FAIL from render-gate.mjs with the named reason. A case that comes back clean,
// or fails for a different reason, is reported as a failure of THIS script.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { MARK } from '../src/lib/brand-mark.mjs';

const page = resolve('dist/client/index.html');
if (!existsSync(page)) { console.error('dist/client/index.html missing — run npm run build first'); process.exit(1); }
const original = readFileSync(page, 'utf8');
if (!/data-mark="hero"/.test(original)) { console.error('the built page has no data-mark="hero" — nothing for these cases to mutate'); process.exit(1); }

// Optional case-name substrings as arguments run a subset — each case is a firefox run, so iterating on
// one case should not cost five.
const only = process.argv.slice(2);

// The mutations are BUILT FROM THE GEOMETRY TABLE, not written out as literal markup. Two cases in the first
// version hard-coded the path data of the mark as it was then (`<path d="M62 118 ...">`, `stroke-width="1.6"`),
// and when the mark's geometry changed the mutations stopped matching anything: the selftest went red, which is
// the honest outcome, but it red for "the harness rotted" rather than "the gate cannot fail". Deriving the
// strings from src/lib/brand-mark.mjs means the cases move with the drawing they are breaking.
const dEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// Editing the padding step of the first anchor that declares a control role. Attribute order in the built HTML
// follows the source, so `data-control` precedes `class`; `extra` appends inert classes for the length case.
const shrinkRole = (h, role, from, to, extra = '') =>
  h.replace(new RegExp(`(<a[^>]*data-control="${role}"[^>]*class=")([^"]*)(")`), (m, head, cls, tail) => head + cls.replace(from, to) + extra + tail);
const pathEl = (s) => new RegExp(`<path d="${dEsc(s.d)}"[^>]*></path>`);
const arcs = MARK.shapes.filter((s) => s.role === 'sphere' && s.tag === 'path');
const dashed = MARK.shapes.find((s) => s.dash);
const solidArc = MARK.shapes.find((s) => s.role === 'sphere' && s.tag === 'path' && !s.dash);
const swStroke = MARK.shapes.find((s) => s.sw);
if (!arcs.length || !dashed || !solidArc || !swStroke) { console.error('the geometry table no longer has the shapes these cases expect — re-read src/lib/brand-mark.mjs'); process.exit(1); }

const cases = [
  // **Write a case's anchor on the attribute you care about, never on a whole tag.** A component that grows a
  // `<style>` block has `data-astro-cid-*` stamped on every element Astro renders inside it, which silently
  // un-matched two cases here on 2026-11-04 (PS-4's slot cap landed in a scoped `<style>` in `Schedule.astro`, so
  // its `<ul>` and spans all gained a cid attribute). Both now splice: `/(<ul class="space-y-6)(")/`. The preflight
  // below is what turns the next occurrence of this class from a confusing red gate into a two-line diagnosis.

  // 1. SVG foreign content: a shape that never made it into the DOM. The card hit this for real (D118
  //    lesson 1) and the box still looked fine, so only the count can see it.
  ['mark missing both equator arcs', (h) => arcs.reduce((acc, s) => acc.replace(pathEl(s), ''), h), /shape\(s\) in the document, the geometry table has/],
  // 1b. the far half stops being dashed: same shape count, same strokes, same box, same colours — the mark
  //     still measures as a curved equator and only the dash check can see that the sphere turned inside out.
  ['mark dash missing from the document', (h) => h.replace(` stroke-dasharray="${dashed.dash}"`, ''), /no longer denoted differently from the near half/],
  // 1c. a dash that survives in the table but fuses back into a line at the drawn size: the pattern is smaller
  //     than one device pixel, so the pixels carry no gap (D119's floor, applied to the gap as well as the stroke).
  ['mark dash fused into a solid line', (h) => h.replace(`stroke-dasharray="${dashed.dash}"`, 'stroke-dasharray="0.6 0.5"'), /fuses into a solid line/],
  // 1d. a dash the table never declared — the shape of this failure is the near half being drawn broken, which
  //     hides the side of the sphere the reader is standing on.
  ['mark dash the table does not declare', (h) => h.replace(pathEl(solidArc), (m) => m.replace(/^<path d="[^"]*"/, (head) => `${head} stroke-dasharray="6 5"`)), /paints dash .* but the geometry table declares none/],
  // 2. a stroke painted the same colour as the ground: every box is right, one shape is invisible. Two
  //    things this case got wrong the first time, both worth keeping in mind:
  //      - an injected CLASS does nothing, because Tailwind's CSS was generated by scanning source at
  //        build time and never saw the new class (the D110 coupling, in reverse). A presentation
  //        attribute with no colour class is what the browser actually paints.
  //      - the ground here is PAPER (the hero sits on sand), not the card's ink. A dark green stroke is
  //        the strongest thing on this surface, not the faintest.
  ['mark stroke painted into the ground', (h) => h.replace('class="fill-none stroke-gold"', 'class="fill-none" stroke="#f7f5f1"'), /under the 3\.0 graphic bar/],
  // 3. the hero column stopped drawing a mark at all — the gate must notice an empty hero, not just a
  //    badly drawn one (this is the D108 rule: missing content is a defect, never a blank).
  ['no mark in the page', (h) => h.replace('data-mark="hero"', 'data-nothing="hero"'), /draws no mark at all/],
  // 4. a box that lost the viewBox ratio: the mark squashes and every class still resolves, because "the
  //    class exists" was never "the box is the shape". Inline style, for the same reason as case 2 —
  //    `h-24` is not in the built CSS unless some source asked Tailwind for it.
  ['mark box off the viewBox ratio', (h) => h.replace('data-mark="hero" viewBox="0 0 240 150"', 'data-mark="hero" style="height: 96px" viewBox="0 0 240 150"'), /box is .* but the viewBox says/],
  // 5. a stroke under one device pixel: it paints *something*, and the colour pair still clears 3.0, but
  //    no pixel is fully covered so it has no measurable colour identity (D119, for line art).
  ['mark stroke under 1px on screen', (h) => h.replace(`stroke-width="${swStroke.sw}"`, 'stroke-width="0.05"'), /stroke lands at [\d.]+px on screen/],
  // 5b. the same floor on the shape the floor is NOT supposed to look at: the meeting point is a filled disc
  //     (`stroke-none`), so the cascade's `stroke-width` is the SVG initial 1 and nothing strokes. The gate now
  //     skips it — and this case is what stops that skip from being a hole: give the disc a REAL stroke under 1px
  //     and it must fail exactly like a line does. A presentation attribute, not a class (case 2's lesson).
  ['meeting point given a real stroke under 1px', (h) => h.replace(
    new RegExp(`(<circle cx="${MARK.dot.cx}" cy="${MARK.dot.cy}" r="${MARK.dot.r}") class="stroke-none `),
    (m, el) => `${el} stroke="#101014" stroke-width="0.3" class="`), /stroke lands at [\d.]+px on screen/],
  // 6. controls, by the ROLE the markup declares (D140). These three are the counterfactual for the pair of
  //    rules that used to match on class substrings: design/records/0016 measured three shipped 40px tap
  //    targets the gate never saw, because the probe truncated `cls` at 120 characters and the class the rules
  //    looked for sat past the cut. An attribute cannot be truncated out of existence.
  //    The mutations edit the class of the first anchor carrying that role — height is padding-derived, so
  //    changing the padding step changes the measured height without inventing markup the CSS would ignore
  //    (D110: an injected class Tailwind never saw paints nothing; `py-2` and `py-3` exist in the built CSS
  //    because real source asks for them).
  ['primary control at the wrong height', (h) => shrinkRole(h, 'primary', 'py-4', 'py-2'), /primary control .* is 32px tall, not 48/],
  // 6b. a button-shaped element that stopped naming its role: the height rules have nothing to match it to,
  //     so the omission is the finding (this is the case that makes D140 enforceable rather than a convention).
  ['control-shaped element with no role', (h) => h.replace(/(<a[^>]*?) data-control="primary"/, '$1'), /declares no data-control role/],
  // 6c. the truncation case itself: a 40px secondary wearing a 200-character class list. The filler classes are
  //     inert (Tailwind generated no CSS for them) — the point is that LENGTH can no longer hide a control from
  //     its height rule.
  ['secondary control behind a 200-character class', (h) => shrinkRole(h, 'secondary', 'py-4', 'py-3', ' ' + 'x-long-filler-class-'.repeat(14)), /secondary control .* is 40px tall, not 48/],
  // 6d. one boundary (operator ruling, 2026-11-03). This is the Discord island's real failed-branch markup with
  //     the old `Try again` put back: a filled, ringed, 48px box sitting inside the notice's own ring. There is
  //     no notice on `/` in the shipped page, so the case plants the whole block — and the planted block is
  //     otherwise legal (1px inset ring, 4.5 text, 48px+ tall), so the failure can only come from the
  //     boundary rule.
  ['a block action inside a notice', (h) => h.replace('</body>', '<div role="alert" class="inset-shadow-rule rounded-control px-4 py-3 min-h-20"><p class="text-body text-ink">The channel summaries did not load.</p><button class="mt-3 inline-flex items-center justify-center px-4 py-4 rounded-control inset-shadow-rule bg-paper text-ink text-label font-medium">Try again</button></div>'), /notice contains a block action/],
  // 7. inset rings (D149-3c + record 0018). The `keylines` rule above cannot see this system's own hairline at
  //    all, because a ratified keyline is a 1px INSET box-shadow, not a border — so before these two cases the
  //    ring grammar had no counterfactual: nothing in the gate could fail on it.
  //    7a. the shipped defect, planted: the hero secondary's fill moved to `panel` while it stands on `paper`, so
  //        its ring reads 2.88 on one side and 3.01 on the other. That is what JoinCommunity's "Join the chat"
  //        measured before the placement fix — and the single number printed next to such a control looks legal.
  //        The mutation swaps a real class for a real class (`bg-panel` is in the built CSS because the join band
  //        asks for it), so nothing about the harness is doing the painting here.
  ['ring straddling two grounds', (h) => h.replace(/(<a[^>]*data-control="secondary"[^>]*class="[^"]*?)bg-paper/, '$1bg-panel'), /may not straddle two grounds/],
  // 7b. a ring that is one-ground but on the WRONG ground: the notice keeps its no-fill grammar and its 1px inset
  //    ring, and only the strip behind it is tinted. Both sides then read 2.88 — under the bar `--color-rule`
  //    was solved to clear (3.01 on paper). This is why the rule is a pair and not a token grep.
  // Re-pointed 2026-11-04: this used to tint the strip behind the schedule section's empty-state notice, and
  // the notice is only in the built page when the calendar holds no upcoming date (data/events.json now holds
  // two, so the markup the mutation targeted stopped existing and the case proved nothing — the gate's own
  // message says so). It now tints the list the schedule rows sit on: each row is a 1px `--color-rule` inset
  // ring with no fill of its own, so both sides of that ring become `panel`, where record 0018's table says
  // the token reads 2.88 — under the 3.0 bar the token was solved to clear on paper. Same rule, real markup.
  // Both cases below match on the CLASS, not on a whole tag. That is not style: a component that grows a
  // `<style>` block gets a `data-astro-cid-*` attribute on every element it renders, and on 2026-11-04 PS-4's
  // slot cap landing in a scoped `<style>` in `Schedule.astro` silently un-matched both — each case printed
  // "the mutation matched nothing ... this case proves nothing", which is the only honest way for a planting
  // to fail. Match the attribute you care about and splice, and added attributes cannot void a case.
  // R6 (D214) re-anchored this case: it used to match `<ul class="space-y-6"` and the ruling changed that
  // utility to `space-y-4`, which is the same failure mode as the cid bug one line up — the class list is
  // exactly what a spacing ruling edits. `data-art-cap` is the schedule list's intentional handle (the same
  // attribute `design/grill/rhythm-variants.mjs` selects on), so anchor here and keep mutating the class.
  ['ring on a tint', (h) => h.replace(/<ul class="([^"]*"[^>]*data-art-cap="323")/, '<ul class=" bg-panel $1'), /under the 3\.0 graphic bar/],
  // The leak this rule exists for (D181): the exact bytes a `//` comment produced in the built card on 2026-11-04,
  // re-inserted at the same place. Without this planting, "comments never ship" is a hope, not a check.
  ['leaked // comment in a card', (h) => h.replace(/(<span class="text-label text-ink-3"[^>]*>)/, '$1// One text node, so the render gate sees one measurement'), /begins like source-comment syntax/],
  // 8. the sign-up cluster (S019, D272). DESIGN.md says the links under a printed date are a quiet label:
  // 32px tall, label tier, no fill, no keyline, no control role. Those are four numbers a class grep cannot
  // see, so each is planted here. All three anchors are on `data-rsvp-cluster` / `data-rsvp-platform` rather
  // than on the class list, for the reason the cases above record (D190): a spacing ruling edits a class,
  // an attribute is what the component owns.
  ['sign-up cluster given a fill', (h) => h.replace(/(<div class=")([^"]*)(" data-rsvp-cluster)/, '$1bg-panel $2$3 data-rsvp-cluster'), /sign-up cluster on .* paints a fill/],
  ['sign-up cluster given its own ring', (h) => h.replace(/(<div class=")([^"]*)(" data-rsvp-cluster)/, '$1inset-shadow-rule $2$3 data-rsvp-cluster'), /sign-up cluster on .* carries its own inset ring/],
  ['sign-up label loses its 32px box', (h) => h.replace('min-h-8 inline-flex items-center gap-1 text-label', 'inline-flex items-center gap-1 text-label'), /sign-up link .* is [\d.]+px tall — the quiet label reserves min-h-8/],
  ['sign-up label promoted to a control', (h) => h.replace(/ data-rsvp-platform="Meetup"/, ' data-control="primary" data-rsvp-platform="Meetup"'), /primary control .* is 32px tall, not 48/],
];

const selected = only.length ? cases.filter(([name]) => only.some((o) => name.includes(o))) : cases;
if (!selected.length) { console.error(`no case matches ${only.join(' ')}. cases: ${cases.map(([n]) => n).join(', ')}`); process.exit(2); }

// Preflight: **every case's mutation must change the page, and that is checkable with string operations.** Running
// it before the browser costs milliseconds and turns a rotted planting into a named, one-line diagnosis instead of
// one confusing firefox FAIL per case (each case is a page load, so the old path cost minutes and pointed at the
// page rather than at the probe). A planting that matches nothing does not prove the rule can fail, so it is fatal
// here rather than a note - and the fix is to re-read the built HTML, never to delete the case.
const rotted = [];
for (const [name, mutate] of selected) {
  try {
    if (mutate(original) === original) rotted.push(name);
  } catch (e) {
    rotted.push(`${name} (the mutation threw: ${e.message})`);
  }
}
if (rotted.length) {
  console.error(`\nSELFTEST PREFLIGHT: FAIL — ${rotted.length} case(s) match nothing in the built page, so they prove nothing:`);
  for (const n of rotted) console.error(`  - ${n}`);
  console.error(`\nThe markup moved. Look at what the build actually makes now, and re-anchor the case on the ATTRIBUTE it\ncares about (not a whole tag: a <style> block in a component stamps data-astro-cid-* on every element in\nit, D190 — and never write a backtick inside these template literals, which is the same bug class):\n  grep -o '<[^>]*class="[^"]*space-y[^"]*"[^>]*>' dist/client/index.html | sort -u\nRe-point the case in this file. Deleting it is how a rule silently stops being gated (D173).`);
  process.exit(1);
}
console.log(`selftest preflight: ${selected.length} case(s), every anchor present in the built page`);

const lines = [];
let ok = true;
try {
  for (const [name, mutate, want] of selected) {
    const mutated = mutate(original);
    if (mutated === original) {
      ok = false;
      lines.push(`  FAIL  selftest "${name}": the mutation matched nothing in the built page, so this case proves nothing (the markup moved — re-read the built HTML)`);
      continue;
    }
    writeFileSync(page, mutated);
    let out = '';
    let failed = false;
    try {
      out = execFileSync(process.execPath, ['design/render-gate.mjs', '/', '--no-build'], {
        encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 180000,
        env: { ...process.env, RENDER_WIDTHS: '1240' },
      });
    } catch (e) {
      out = `${e.stdout ?? ''}${e.stderr ?? ''}`;
      failed = e.status !== 0;
    }
    const hits = out.split('\n').filter((l) => l.startsWith('FAIL'));
    const match = hits.find((l) => want.test(l));
    if (!failed || !hits.length) {
      ok = false;
      lines.push(`  FAIL  selftest "${name}": the gate PASSED on a page with a broken mark — that check is not a check`);
    } else if (!match) {
      ok = false;
      lines.push(`  FAIL  selftest "${name}": the gate failed, but not for ${want}: ${hits[0].slice(0, 150)}`);
    } else {
      lines.push(`  ok    selftest "${name}": fails as designed — ${match.slice(6, 150)}`);
    }
  }
} finally {
  writeFileSync(page, original);
}

console.log('\n== can check:render\'s mark and control checks fail? (mutated built page) ==');
console.log(lines.join('\n'));
console.log(`\n  (the real page is restored; re-run \`npm run check:render\` to see it green)`);
if (!ok) { console.error('RENDER GATE SELFTEST: FAIL'); process.exit(1); }
console.log('RENDER GATE SELFTEST: PASS');
