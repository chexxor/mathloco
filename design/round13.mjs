// One box out of one screenshot, at 1:1 device pixels. Every picture in the specimen goes through here, so
// "this image is the box the probe reported" is a property of the code, not of the caption.
async function cropBox(png, box, file, pad, where) {
  if (!existsSync(png) || !box) { report.notes.push(`${where}: no shot or no measured box — no picture for this one`); return null; }
  const meta = await sharp(png).metadata();
  // sharp's extract wants integers and the probe posts fractional boxes; rounding outward keeps the whole box
  // inside the crop rather than shaving a pixel off the edge it is measuring.
  const left = Math.max(0, Math.floor(box.x - pad)), top = Math.max(0, Math.floor(box.y - pad));
  const width = Math.min(meta.width - left, Math.ceil(box.x + box.w + pad) - left);
  const height = Math.min(meta.height - top, Math.ceil(box.y + box.h + pad) - top);
  if (width < 50 || height < 50) { report.notes.push(`${where}: box ${width}x${height} inside a ${meta.width}x${meta.height} shot — refusing to crop a box the shot does not hold`); return null; }
  await sharp(png).extract({ left, top, width, height }).png({ effort: 8 }).toFile(file);
  return file;
}

// Does the stroke ARRIVE in the pixels? The gate reports `stroke-width x scale` in device px, which is arithmetic
// about paint; `vector-effect: non-scaling-stroke` is exactly the case where the arithmetic and the paint disagree.
// So measure the paint: run a horizontal scanline across a VERTICAL line of the mark — the left meridian, drawn at
// viewBox x=94 from y 59 to 84, the only stroke there that is truly vertical, so a horizontal cut across it equals
// its stroke width and not stroke-width/sin(angle). The ground is the MODAL colour inside the mark's own box (line
// art covers a few percent of its box, so what the box is mostly made of is what the mark sits on): sampling a fixed
// offset outside the box landed inside the Byrne plate for the row variants, and every stroke then read as ink.
// Every ink run in the window is reported, so the number can be checked rather than trusted.
// The scan runs on the FULL-PAGE shot: the probe's boxes are page-absolute, and scanning the hero crop with page
// coordinates lands 200px off the mark and reports an honest-looking zero.
async function paintedStroke(variantId, markBox) {
  const shotPath = `${SCRATCH}/page-1240.png`;
  if (!existsSync(shotPath) || !markBox) return { paintedPx: null, reportedPx: null, why: 'no shot/box' };
  const { info, data } = await sharp(shotPath).raw().toBuffer({ resolveWithObject: true });
  const scale = markBox.w / MARK.vbW;
  const minSw = Math.min(...MARK.shapes.map((s) => s.sw).filter(Boolean));
  const reportedPx = +(minSw * scale).toFixed(2);
  if (!scale) return { paintedPx: null, reportedPx, why: 'no scale' };
  const at = (x, y) => {
    if (x < 0 || y < 0 || x >= info.width || y >= info.height) return null;
    const o = (y * info.width + x) * info.channels;
    return [data[o], data[o + 1], data[o + 2]];
  };
  if (!VERTICAL) { report.notes.push(`${variantId}: the geometry table holds no vertical stroke, so there is nothing to scan across — no painted-stroke number`); return { paintedPx: null, reportedPx, why: 'no vertical stroke in the table' }; }
  const cx = Math.round(markBox.x + VERTICAL.x * scale), cy = Math.round(markBox.y + VERTICAL.y * scale);
  // the ground this mark sits on, by census of its own box
  const hist = new Map();
  for (let y = Math.round(markBox.y); y < Math.round(markBox.y + markBox.h); y++) {
    for (let x = Math.round(markBox.x); x < Math.round(markBox.x + markBox.w); x++) {
      const p = at(x, y);
      if (!p) continue;
      const k = ((p[0] >> 3) << 6) | ((p[1] >> 3) << 3) | (p[2] >> 3);
      const e = hist.get(k) || { n: 0, r: 0, g: 0, b: 0 };
      e.n++; e.r += p[0]; e.g += p[1]; e.b += p[2];
      hist.set(k, e);
    }
  }
  const top = [...hist.values()].sort((a, b) => b.n - a.n)[0];
  if (!top) { report.notes.push(`${variantId}: the mark's box holds no pixels — no painted-stroke number`); return { paintedPx: null, reportedPx, why: 'empty box' }; }
  const gnd = [top.r / top.n, top.g / top.n, top.b / top.n];
  const g = oklabBytes(...gnd);
  report.notes.push(`${variantId}: the mark's ground, by census of its own box, is rgb(${gnd.map((v) => v.toFixed(0)).join(',')}) at ${Math.round(100 * top.n / (markBox.w * markBox.h))}% of the box`);
  const inkAt = (x) => { const p = at(x, cy); return p ? distLab(oklabBytes(...p), g) : 0; };
  const runsAt = (bar) => {
    const out = [];
    let run = null;
    for (let d = -16; d <= 16; d++) {
      if (inkAt(cx + d) >= bar) run = run ? { ...run, w: run.w + 1, to: d } : { from: d, to: d, w: 1 };
      else if (run) { out.push(run); run = null; }
    }
    if (run) out.push(run);
    return out;
  };
  const runs = runsAt(SAME_COLOUR_BAR);              // includes antialiased pixels
  const core = runsAt(0.10);                          // pixels that are mostly ink
  const mine = (list) => { const r = list.find((r) => r.from <= 0 && r.to >= 0); return r ? r.w : null; };
  // the peak, against what full coverage of this stroke's own token would read on this ground
  const tok = MARK_COLOURS.paper[VERTICAL.shape.role];
  const ceiling = distLab(tokenLab(tok), g);
  const peak = Math.max(...Array.from({ length: 33 }, (_, i) => i - 16).map((d) => inkAt(cx + d)));
  return {
    paintedPx: mine(runs), corePx: mine(core), reportedPx, minSw, scale: +scale.toFixed(3), scanX: cx, scanY: cy,
    scanRole: VERTICAL.shape.role, scanToken: tok, scanSw: VERTICAL.shape.sw,
    scanPx: +(VERTICAL.shape.sw * scale).toFixed(2),
    ground: gnd.map((v) => Math.round(v)), groundShare: +(top.n / (markBox.w * markBox.h)).toFixed(3),
    allRuns: runs.map((r) => `${r.from}..${r.to}`).join(' '),
    peakInk: +peak.toFixed(3), ceiling: +ceiling.toFixed(3), coverage: +(peak / ceiling).toFixed(3),
  };
}

// --------------------------------------------------------------------- the mutations
function writeVariant(v) {
  const boxes = plateBoxes({ ...geoRef, aspect: report.plates.PS1.aspect });
  let html = original;
  if (v.plate) {
    const b = boxes[v.plate];
    const png = readFileSync(`${SCRATCH}/plate-PS1-${v.plate}-${b.w}x${b.h}.png`).toString('base64');
    const img = `<img data-plate="PS1" alt="Euclid Book I figure, from Byrne's 1847 coloured diagrams (public domain, insideoutlibrary.com)" ` +
      `class="mb-8 block" style="width:100%;aspect-ratio:${b.w} / ${b.h};" src="data:image/png;base64,${png}">`;
    const re = /<div data-placeholder="hero"[\s\S]*?<\/div>/;
    if (!re.test(html)) throw new Error(`${v.id}: no PS-1 placeholder div in the built page`);
    html = html.replace(re, img);
  }
  if (v.ps3) {
    const b = report.plates.PS3.boxes.ruled;
    const png = readFileSync(b.png).toString('base64');
    const img = `<img data-plate="PS3" alt="Euler's thirty-six officers diagram, from Plane geometry (1910), public domain, insideoutlibrary.com" ` +
      `class="block" style="width:100%;aspect-ratio:${b.w} / ${b.h};" src="data:image/png;base64,${png}">`;
    const re = /<div data-placeholder="(?!hero)[^"]*"[\s\S]*?<\/div>/;
    if (!re.test(html)) throw new Error(`${v.id}: no PS-3 placeholder div in the built page`);
    html = html.replace(re, img);
  }
  if (v.moveMark) {
    const re = /<svg data-mark="hero"[\s\S]*?<\/svg>/;
    const m = html.match(re);
    if (!m) throw new Error(`${v.id}: no hero mark svg to move`);
    html = html.replace(re, '');
    if (!/<h1/.test(html)) throw new Error(`${v.id}: no h1 to place the mark before`);
    html = html.replace(/<h1/, `${m[0]}<h1`);
  }
  if (v.attribute === 'non-scaling-stroke') {
    // Every stroke, not the first one, and inserted AFTER the quoted value. Two ways this went wrong before it went
    // right: one lazy regex over the whole page matched 1 of 7 strokes and stopped (the variant then measured
    // identical to the row it was supposed to differ from), and inserting the attribute inside the value produced
    // `stroke-width=" vector-effect="non-scaling-stroke"1.3"` — an invalid value, so every stroke fell back to the
    // SVG initial 1 and the gate failed seven times for a reason that was my mutation, not the design. Both were
    // visible only because the numbers disagreed with what the variant claims to do.
    const m = html.match(/<svg data-mark="hero"[\s\S]*?<\/svg>/);
    if (!m) throw new Error(`${v.id}: no hero mark svg to pin`);
    const pinned = m[0].replace(/stroke-width="[^"]*"/g, (s) => `${s} vector-effect="non-scaling-stroke"`);
    const n = (m[0].match(/stroke-width="[^"]*"/g) || []).length;
    if (n !== MARK.shapes.length) throw new Error(`${v.id}: the built mark carries ${n} stroke-width attributes, the geometry table has ${MARK.shapes.length} stroked shapes — pinning them all is the whole variant, so a moved mark means re-reading the built HTML`);
    if ((pinned.match(/vector-effect="non-scaling-stroke"/g) || []).length !== n) throw new Error(`${v.id}: ${n} strokes to pin but the pin landed on fewer — refusing to measure a mark whose markup the mutation broke`);
    html = html.replace(m[0], () => pinned);
  }
  if (v.css) html = html.replace('</head>', `<style id="r13-${v.id}">${v.css}</style></head>`);
  if (html === original) throw new Error(`${v.id}: the mutation changed nothing — this measurement would describe the wrong page`);
  writeFileSync(PAGE, html);
}
