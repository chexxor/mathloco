#!/usr/bin/env node
// round13.mjs — grill round 13 in one command: the hero media column, measured on the real page under each
// composition option, and a specimen the operator chooses from by looking.
//
//   npm run round13                                  all variants, the full loop (~2-3 min)
//   npm run round13 -- stack-fill plate-owns-slot    a subset, by id
//   npm run round13 -- --widths 1240                 fewer geometry widths (the gate keeps its own matrix)
//
// Why it exists. A2 (the two ruled plates on the real page) is blocked on one operator ruling: in PS-1 the
// Byrne plate and the club's mark sit in the same `lg:flex` column, so a plate crowds the mark below its own
// legibility floor — measured on the review build, `check:render` prints eight FAILs and the mark falls to
// 152x95 with 0.81px strokes (D119's floor is 1px). That is a composition decision, and a composition
// decision cannot be ruled from numbers in a terminal. So this script makes the artifact the ruling needs:
// the SAME built page, holding the REAL plate at the REAL size, shot under each option, with the gates' own
// numbers beside every picture.
//
// What it does, in order:
//   1. plants the placeholder overlay (the review state — the only state in which a reserved photo slot has a
//      box standing in it) and builds, then ASSERTS the built page carries data-placeholder, as
//      scripts/review-render.mjs does. A review build whose overlay silently failed would measure the shipped
//      page and print PASS about a page that was never built.
//   2. crops the ruled Byrne leaf at each candidate box (sharp, `attention` cover fit at 2x — the same crop
//      design/grill/round12-build.mjs measured the art shortlist with, from the same cached source bytes), so
//      the plate in every screenshot is the plate record 0023 priced, not a hatch.
//   3. per variant: mutate dist/client/index.html (a <style> block, an <img> swap, and where the variant
//      calls for it a DOM move of the mark), then measure with the EXISTING instruments — check:space for the
//      boxes, check:render for the mark's legibility verdict, check:color for what the plate costs the palette
//      — and crop the hero out of the screenshot the survey already took from that same load.
//      No new gate logic anywhere: the FAILs are the gate's own rules, so a specimen can never disagree with CI.
//   4. restore: the original page after every variant, the overlay and the shipped build at the end, then the
//      two surveys re-run on the SHIPPED page so the scratch reports left behind describe the tree rather than
//      a state that is not allowed to ship.
//   5. write design/grill/round13/report.json, then generate design/grill/round-13-hero.html from it. The
//      builder reads the report and throws on a missing lookup: nothing in the specimen is transcribed by hand.
//
// dist/ is gitignored and regenerated by `npm run build`, so mutating it mutates no artifact — the same
// technique design/render-gate-selftest.mjs uses to prove a gate can fail. A mutation that changes nothing
// THROWS, because a silent no-op is how a measurement starts describing the wrong page.
//
// Cost, measured on this rig (Linux, native, Firefox 159): the whole 7-variant loop ~2.5 min, of which the
// two astro builds are ~10 s. It is a design round, not a gate: nothing here runs in `verify`.
