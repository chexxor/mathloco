// The scan target is the mark's one truly VERTICAL stroke, found in the geometry table rather than remembered:
// `M94 59 L94 84` is a vertical run, so a horizontal cut across it equals its stroke width and not
// stroke-width / sin(angle). If the drawing stops containing a vertical segment the probe says so instead of
// measuring a slanted line and calling the number a stroke width.
const VERTICAL = (() => {
  for (const sh of MARK.shapes) {
    const m = sh.tag === 'path' && sh.d.match(/^M([\d.]+) ([\d.]+) L\1 ([\d.]+)/);
    if (m) return { shape: sh, x: +m[1], y: (+m[2] + +m[3]) / 2 };
  }
  return null;
})();

// What the token this stroke is painted with WOULD read against the ground, fully covering the pixel. D119's claim
// is about coverage, so a peak ink number means nothing without its ceiling; the token is read out of the theme
// block, because a ceiling remembered from a retuned token is a made-up number.
function tokenLab(name) {
  const m = readFileSync('src/styles/global.css', 'utf8').match(new RegExp(`--color-${name}:\\s*oklch\\(([^)]*)\\)`));
  if (!m) throw new Error(`no --color-${name} in src/styles/global.css — the token moved, and a coverage ceiling that predates the move is not a measurement`);
  const [L, C, h] = m[1].trim().split(/[\s,]+/).map((v) => (v.endsWith('%') ? parseFloat(v) / 100 : parseFloat(v)));
  const rad = (h * Math.PI) / 180;
  return [L, C * Math.cos(rad), C * Math.sin(rad)];
}

