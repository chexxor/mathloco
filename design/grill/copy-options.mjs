/**
 * The edit an option would apply, as ordered `[from, to]` pairs against the BUILT page.
 *
 * Order matters: the h1 goes first. It used to matter for a second reason — the pre-rename h1 markup
 * (`Minneapolis Math<!-- -->&nbsp;<br …>Book Club`) did not contain the literal shipped name, so a name sweep run
 * first would have left a half-renamed h1 behind and still "succeeded". Keep the order anyway: a future wordmark
 * may again be broken across elements.
 *
 * Throws on a pair that matches nothing (round 13's rule: a silent no-op is how a measurement starts describing
 * the page it was supposed to change), and on a pair whose `from` or `to` reaches an org-of-record string.
 */
export function mutations(option) {
  const name = option.name ?? SHIPPED.name;
  const h1 = option.h1 ?? SHIPPED.h1;
  const locator = option.locator ?? SHIPPED.locator;
  const band = option.band ?? SHIPPED.band;
  const pairs = [];
  if (h1 !== SHIPPED.h1) pairs.push({ where: 'h1', from: SHIPPED.h1, to: h1 });
  if (name !== SHIPPED.name) pairs.push({ where: 'name slots', from: SHIPPED.name, to: name });
  if (locator !== SHIPPED.locator) pairs.push({ where: 'locator', from: SHIPPED.locator, to: locator });
  if (band !== SHIPPED.band) pairs.push({ where: 'band lede', from: SHIPPED.band, to: band });
  // Options that mutate somewhere other than the four canonical slots (the continuity line, say) name their own
  // pair. Ordered last, so a sweep that would rewrite the inserted string is visible as one.
  for (const p of option.extra ?? []) pairs.push(p);
  for (const p of pairs) {
    for (const t of ORG_OF_RECORD) {
      if (p.from.includes(t) || p.to.includes(t)) {
        throw new Error(`round16: option "${option.label}" would edit ${t} \u2014 the org-of-record string is not this site's to rename`);
      }
    }
  }
  return pairs;
}

/** Apply the pairs to one HTML string; throws if any pair matched nothing. Returns the per-pair match counts. */
export function apply(html, option, where = 'page') {
  const counts = [];
  let out = html;
  for (const p of mutations(option)) {
    const n = out.split(p.from).length - 1;
    if (!n) throw new Error(`round16: option "${option.label}" matched nothing in ${where} \u2014 "${p.from.slice(0, 60)}" (${p.where})`);
    out = out.split(p.from).join(p.to);
    counts.push({ where: p.where, matches: n });
  }
  for (const t of ORG_OF_RECORD) {
    if (html.includes(t) && !out.includes(t)) throw new Error(`round16: option "${option.label}" removed ${t} from ${where}`);
  }
  return { html: out, counts };
}
