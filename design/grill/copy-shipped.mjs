// Re-derives the SHIPPED baseline in design/grill/copy-options.mjs from the page the tree actually built.
//
// Why this exists: a naming round mutates the built HTML by literal string, so a baseline that has drifted from
// `dist/` does not measure the site — it measures a site that no longer exists, and it fails loudly (apply() throws
// when a pair matches nothing) only after every page copy has been built. The rename to Matheapolis on 2026-11-07
// made that drift certain: the h1 lost its `&nbsp;` tie and its `<br>`, the locator changed, and the band clause
// changed. Re-basing by hand means reading built HTML and pasting it, which is how a specimen ends up quoting a
// string no page ships. So the baseline is extracted, never typed.
//
// Usage: npm run build && node design/grill/copy-shipped.mjs   (then `npm run round16`)
// It rewrites only the region between the SHIPPED markers in copy-options.mjs. Everything else in that file — the
// option set, ORG_OF_RECORD, the mutation order — is authored by hand and stays.
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const htmlPath = resolve(root, 'dist/client/index.html');
const target = resolve(root, 'design/grill/copy-options.mjs');
if (!existsSync(htmlPath)) {
  console.error('copy-shipped: no dist/client/index.html. Run `npm run build` first.');
  process.exit(1);
}
// A baseline extracted from a build older than the copy it describes is the same lie in a different costume.
const newest = ['package.json', 'src/components/HeroSection.astro', 'src/components/Schedule.astro', 'src/config.json']
  .map((f) => ({ f, m: statSync(resolve(root, f)).mtimeMs }))
  .sort((a, b) => b.m - a.m)[0];
if (statSync(htmlPath).mtimeMs < newest.m) {
  console.error(`copy-shipped: dist/client/index.html is older than ${newest.f} — rebuild before re-basing.`);
  process.exit(1);
}

const html = readFileSync(htmlPath, 'utf8');
const grab = (label, re) => {
  const m = re.exec(html);
  if (!m) {
    console.error(`copy-shipped: no ${label} in dist/client/index.html — the page changed shape; update the anchor.`);
    process.exit(1);
  }
  return m[1] ?? m[0];
};

const config = JSON.parse(readFileSync(resolve(root, 'src/config.json'), 'utf8'));
const shipped = {
  name: config.seo.name,
  h1: grab('the h1', /<h1 class="mt-1 text-display-1[^>]*>[\s\S]*?<\/h1>/),
  locator: grab('the hero locator', /<span class="text-ink-3">([^<]*)<\/span>/),
  // The band lede, in whichever form the page ships: the 2026-11-08 ruling deleted its second sentence, and an
  // anchor that requires the deleted clause is an anchor that fails the build it is meant to measure. The optional
  // half is kept so a restored clause is re-based, not a crash.
  band: grab('the schedule band lede', /The sign-up is on Meetup,[\s\S]*?calendar\.(?: What happens at the table[\s\S]*?lecturing\.)?/),
  formerly: grab('the continuity sentence', /Formerly the Minneapolis Mathematics Book Club\./),
  footerAnchor: grab('the footer place line', /<p class="mt-6 text-micro">Minneapolis, Minnesota<\/p>/),
};

const block = [
  '// <shipped>  generated by design/grill/copy-shipped.mjs from dist/client/index.html — do not hand-edit,',
  '// regenerate (`npm run build && npm run round16:base`). Every string here is a literal the round replaces, so',
  '// a byte that has drifted from the build makes the round measure a page that does not exist.',
  'export const SHIPPED = ' + JSON.stringify(shipped, null, 2) + ';',
  '// </shipped>',
].join('\n');

const src = readFileSync(target, 'utf8');
const start = src.indexOf('// <shipped>');
const end = src.indexOf('// </shipped>');
if (start < 0 || end < 0) {
  console.error('copy-shipped: copy-options.mjs has no <shipped> markers — add them around the SHIPPED block.');
  process.exit(1);
}
writeFileSync(target, src.slice(0, start) + block + src.slice(end + '// </shipped>'.length));
console.log(`copy-shipped: baseline re-based from the build — h1 ${JSON.stringify(shipped.h1).slice(0, 74)}…`);
console.log(`  locator ${JSON.stringify(shipped.locator)}  band ${shipped.band.length} chars  formerly ${JSON.stringify(shipped.formerly)}`);
