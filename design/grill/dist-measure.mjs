#!/usr/bin/env node
// dist-measure.mjs — measure the BUILT pages in Firefox without a web server.
//
//   node design/grill/dist-measure.mjs <distDir> <route> <measure.js> [width] [height] [shotOut.png]
//   e.g. node design/grill/dist-measure.mjs dist/client / design/grill/render-measure.js 1240 1400
//
// The optional shotOut.png is firefox's own screenshot of the same page the measure script reported on —
// which is what makes "what did this stroke actually paint" answerable for a built page rather than only
// for a specimen (the share card's gate, D116/D118, is built on exactly that pairing: pixels plus the
// page's own report of where it laid things out).
//
// Why this exists next to page-measure.mjs: Astro writes every asset URL absolute — `/_astro/...` in
// href/src/srcset AND `url(/_astro/...)` inside the built CSS — and a file:// page resolves `/` at the
// filesystem root, so a copied dist/client/index.html loads with no CSS and no @font-face and every
// measurement is wrong. Serving dist over loopback http was tried first and measured as a failure on
// this rig: under `--screenshot` firefox fetches `GET /` and then never fetches the subresources, and
// the run dies at the timeout (Linux/x64, Firefox 158.0.1). So: rewrite the URLs to relative, in copies
// that sit inside dist, and let page-measure.mjs do the browser part exactly as it does for a specimen.
//
// Copies are named `.rel.css` / `rendered-*.html` and are never written over an artifact: dist/ is
// regenerated by `npm run build`, and a measurement step must not mutate what gets deployed.
//
// What it does NOT cover: an island's client-side FETCH (there is no API on file://). Islands do hydrate
// here — Astro's island chunk is fetched from the relative `_astro/...` copy, and its `$effect` runs — so
// a probe can measure a browser-side state change. The server-rendered branch is still what a
// JavaScript-off visitor sees, and DESIGN.md requires that branch to exist regardless.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, unlinkSync, renameSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, resolve, basename, dirname } from 'node:path';

// Flags are separated from the positionals so a probe can pass setup code without shifting the
// width/height slots. `--prelude <file>` injects that file as a classic inline <script> BEFORE the
// measure script: a classic script runs at document parse time, and an island's runtime is registered
// before it, so the prelude is the way a gate puts a value in localStorage before any island hydrates
// (the state a returning visitor is actually in). Used by scripts/check-rsvp-preference.mjs (D281).
const rawArgs = process.argv.slice(2);
const positional = [];
let preludePath = null;
for (let i = 0; i < rawArgs.length; i++) {
  if (rawArgs[i] === '--prelude') { preludePath = rawArgs[++i]; continue; }
  if (rawArgs[i].startsWith('--')) continue;
  positional.push(rawArgs[i]);
}
const [distArg, route = '/', measureArg, w = '1240', h = '1400', shotOut] = positional;
if (!distArg || !measureArg) {
  console.error('usage: node design/grill/dist-measure.mjs <distDir> <route> <measure.js> [w] [h] [shot] [--prelude <file>]');
  process.exit(2);
}
if (preludePath && !existsSync(resolve(preludePath))) {
  console.error(`--prelude ${preludePath} does not exist`);
  process.exit(2);
}
const dist = resolve(distArg);
const assetDir = join(dist, '_astro');
if (!existsSync(assetDir)) { console.error(`no _astro directory under ${dist} — run npm run build first`); process.exit(2); }

// 1. rewritten CSS copies, alongside the originals so `url(./x.woff2)` resolves
let cssCopies = 0;
for (const f of readdirSync(assetDir)) {
  if (!f.endsWith('.css') || f.endsWith('.rel.css')) continue;
  const dest = join(assetDir, f.replace(/\.css$/, '.rel.css'));
  // Skip a copy that is already current: nine runs of the matrix rewriting the same two files is
  // wasted work, and mtime is enough because dist/ is deleted and rebuilt by astro build.
  try {
    if (statSync(dest).mtimeMs >= statSync(join(assetDir, f)).mtimeMs) continue;
  } catch {}
  // The copy lives INSIDE _astro, so a hashed-asset url drops the _astro segment (./x.woff2) and a
  // public-dir url goes up one (../x.png). Getting this wrong is silent and expensive: the woff2 404s,
  // the face sits at "loading" forever, and every height the gate reports is a fallback metric — which
  // is exactly why the gate now fails on a ratified face that never loads.
  const css = readFileSync(join(assetDir, f), 'utf8')
    .replace(/url\((['"]?)\/_astro\//g, 'url($1./')
    .replace(/url\((['"]?)\/(?!\/)/g, 'url($1../');
  // write-then-rename, so a parallel run never reads a half-written stylesheet
  const tmp = `${dest}.writing`;
  writeFileSync(tmp, css);
  renameSync(tmp, dest);
  cssCopies++;
}

// 2. the page copy, with href/src/srcset made relative and the CSS link pointed at the copy
const dir = join(dist, route === '/' ? '' : route.replace(/^\//, ''));
// Astro writes a 404 page as a sibling FILE (404.html), not a directory with index.html
const srcPage = [dir, join(dir, 'index.html'), `${dir}.html`, join(dist, `${route.replace(/^\//, '')}.html`)]
  .find((p) => existsSync(p) && statSync(p).isFile());
if (!srcPage) { console.error(`no page for route ${route} under ${dist}`); process.exit(2); }
const probeDir = dirname(srcPage);
const depth = probeDir === dist ? 0 : probeDir.split('/').length - dist.split('/').length;
const rel = depth === 0 ? './' : '../'.repeat(depth);
// `component-url` and `renderer-url` are in the list on purpose (measured 2026-11-11, Linux, Firefox 159.0,
// native): Astro's Svelte islands carry the island JS in those attributes, and a page copied to file://
// resolves `/_astro/...` at the filesystem root. An island whose chunk 404s hydrates nothing and says
// nothing — the probe just sees the server-rendered bytes, which is exactly the failure `check:rsvp-preference`
// must be able to tell apart from "the island hydrated and did not reorder".
const html = readFileSync(srcPage, 'utf8')
  // `$1` is the attribute up to the quote, NOT the whole match: the whole match includes the leading
  // slash being replaced. Measured 2026-11-11 (Linux, Firefox 159.0): writing the callback as
  // `(m) => m + rel` produced `href="/./_astro/Layout.rel.css`, which a file:// page resolves at the
  // filesystem root, so the stylesheet never loaded and every number the render gate reported was an
  // unstyled page (691 FAILs, controls 22px instead of 48, contrast 1). The capture group is the fix.
  .replace(/((?:href|src|srcset|content|component-url|renderer-url)=")\/(?!\/)/g, (_match, attr) => `${attr}${rel}`)
  .replace(new RegExp(`(${rel})_astro/([A-Za-z0-9._-]+)\\.css`, 'g'), `$1_astro/$2.rel.css`);

// One probe copy per route AND width: the gate runs its route x width matrix in parallel, and three
// runs probing `/` would otherwise write over the same file while reading from it.
const prelude = preludePath ? `<script>${readFileSync(resolve(preludePath), 'utf8')}</script>\n` : '';
const probe = join(probeDir, `rendered-${route === '/' ? 'index' : route.replace(/[\/]/g, '-')}.${w}.html`);
writeFileSync(probe, html.includes('</body>') ? html.replace('</body>', `${prelude}</body>`) : html + prelude);
console.error(`probing ${basename(probe)} — ${cssCopies} rewritten css copies, asset prefix ${rel}`);
try {
  execFileSync(process.execPath, ['design/grill/page-measure.mjs', probe, resolve(measureArg), w, h, ...(shotOut ? [resolve(shotOut)] : [])], { stdio: 'inherit' });
} finally {
  // page-measure removes its own .measured-* copy; this one is ours, and it sits inside the artifact
  // that gets uploaded — never leave a probe file in dist
  try { unlinkSync(probe); } catch {}
}
