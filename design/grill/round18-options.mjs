/**
 * The band section, moved out of the seam between the reasons and the schedule and dropped in just before the
 * footer. The section is matched by what the page NAMES it (its own `aria-label`), never by its styling, and a
 * page that stopped naming it makes this throw rather than measure an unchanged page.
 */
function moveBandBefore(html) {
  const OPEN = /<section class="bg-paper py-12" aria-label="Plate from a public-domain mathematics book"[\s\S]*?<\/section>/;
  const m = html.match(OPEN);
  if (!m) throw new Error('no horizon section to move — the page stopped naming its own plate band, so this option is not applicable at this state');
  const cut = html.replace(OPEN, '');
  const FOOT = /<footer[^>]*>/;
  if (!FOOT.test(cut)) throw new Error('no footer to put the band before');
  return cut.replace(FOOT, `${m[0]}$&`);
}
